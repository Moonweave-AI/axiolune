#!/usr/bin/env node
'use strict';

/**
 * Load an M2 module as a merged envelope (core + profile + binding) or legacy module.yaml.
 * Phase B — ADR-034 / RFC-009.
 */

const fs = require('fs');
const path = require('path');
const yaml = require('js-yaml');

const DOMAIN_CONTAINERS = [
  'objectTypes', 'associationTypes', 'relationTypes', 'attributeTypes',
  'identifierTypes', 'codeLists', 'constraints', 'relationUses', 'constraintBindings',
];

const BINDING_ATTR_RE = new RegExp(
  [
    '/ontology/meta/data-binding/',
    'sourceArtifact',
    'sourceLocator',
    'ContractRef$',
    'ContractDigest$',
    'ProbeRef$',
    'ProbeDigest$',
    'toolLock',
    'runtimeDigest',
    'implementationDigest',
    'VersionSetDigest$',
    'formulaDigest$',
    'normalizationContract',
  ].map(s => `(?:${s})`).join('|'),
);

function isBindingAttribute(iri) {
  if (!iri || typeof iri !== 'string') return false;
  return BINDING_ATTR_RE.test(iri);
}

function loadYamlFile(filePath) {
  if (!filePath || !fs.existsSync(filePath)) return null;
  return yaml.load(fs.readFileSync(filePath, 'utf8'));
}

function fragmentPaths(moduleDir) {
  return {
    legacy: path.join(moduleDir, 'module.yaml'),
    core: path.join(moduleDir, 'module.core.yaml'),
    profile: path.join(moduleDir, 'module.profile.yaml'),
    binding: path.join(moduleDir, 'module.binding.yaml'),
  };
}

function hasEnvelopeFragments(moduleDir) {
  const p = fragmentPaths(moduleDir);
  return fs.existsSync(p.core);
}

function mergeAttributeUses(baseUses, overlayUses) {
  const map = new Map();
  for (const u of baseUses || []) {
    if (u && u.attribute) map.set(u.attribute, { ...u });
  }
  for (const u of overlayUses || []) {
    if (u && u.attribute) map.set(u.attribute, { ...u });
  }
  return [...map.values()].sort((a, b) => String(a.attribute).localeCompare(String(b.attribute)));
}

function mergeContainer(baseContainer, overlayContainer) {
  const out = { ...(baseContainer || {}) };
  if (!overlayContainer) return out;
  for (const [name, overlayDef] of Object.entries(overlayContainer)) {
    if (!overlayDef || typeof overlayDef !== 'object') continue;
    const baseDef = out[name];
    if (!baseDef) {
      out[name] = structuredClone(overlayDef);
      continue;
    }
    const merged = { ...baseDef, ...overlayDef };
    if (baseDef.attributeUses || overlayDef.attributeUses) {
      merged.attributeUses = mergeAttributeUses(baseDef.attributeUses, overlayDef.attributeUses);
    }
    if (baseDef.participantRoles && overlayDef.participantRoles) {
      merged.participantRoles = overlayDef.participantRoles.length
        ? overlayDef.participantRoles
        : baseDef.participantRoles;
    }
    out[name] = merged;
  }
  return out;
}

function mergeDomain(baseDomain, overlayDomain) {
  const out = { ...(baseDomain || {}) };
  if (!overlayDomain) return out;
  for (const container of DOMAIN_CONTAINERS) {
    if (overlayDomain[container]) {
      out[container] = mergeContainer(out[container], overlayDomain[container]);
    }
  }
  return out;
}

function mergeEnvelopeDocs(coreDoc, profileDoc, bindingDoc) {
  if (!coreDoc || !coreDoc.module) {
    throw new Error('module.core.yaml must contain module section');
  }
  let domain = structuredClone(coreDoc.domain || {});
  if (profileDoc?.domain) domain = mergeDomain(domain, profileDoc.domain);
  if (bindingDoc?.domain) domain = mergeDomain(domain, bindingDoc.domain);
  return {
    module: structuredClone(coreDoc.module),
    domain,
  };
}

function loadModuleEnvelope(moduleDir) {
  const p = fragmentPaths(moduleDir);
  if (hasEnvelopeFragments(moduleDir)) {
    const coreDoc = loadYamlFile(p.core);
    const profileDoc = loadYamlFile(p.profile);
    const bindingDoc = loadYamlFile(p.binding);
    return {
      source: 'envelope',
      paths: p,
      doc: mergeEnvelopeDocs(coreDoc, profileDoc, bindingDoc),
    };
  }
  const legacy = loadYamlFile(p.legacy);
  if (!legacy) throw new Error(`No module.yaml or module.core.yaml in ${moduleDir}`);
  return { source: 'legacy', paths: p, doc: legacy };
}

function serializeModuleDoc(doc) {
  const header = '# Generated by scripts/domain/merge-module-envelope.cjs — do not hand-edit.\n'
    + '# Source: module.core.yaml (+ optional profile/binding). Regenerate after fragment edits.\n\n';
  return header + yaml.dump(doc, { lineWidth: 120, noRefs: true, quotingType: '"' });
}

function mergedBytes(moduleDir) {
  const { doc } = loadModuleEnvelope(moduleDir);
  return Buffer.from(serializeModuleDoc(doc), 'utf8');
}

function isMergedStale(moduleDir) {
  const p = fragmentPaths(moduleDir);
  if (!hasEnvelopeFragments(moduleDir) || !fs.existsSync(p.legacy)) return false;
  const onDisk = fs.readFileSync(p.legacy, 'utf8').replace(/^#.*\n(\n#.*\n)*/m, '');
  const fresh = serializeModuleDoc(loadModuleEnvelope(moduleDir).doc).replace(/^#.*\n(\n#.*\n)*/m, '');
  return onDisk !== fresh;
}

function splitAttributeUses(attributeUses) {
  const core = [];
  const binding = [];
  for (const u of attributeUses || []) {
    if (isBindingAttribute(u.attribute)) binding.push(u);
    else core.push(u);
  }
  return { core, binding };
}

function extractBindingDomain(domain) {
  const bindingDomain = {};
  const coreDomain = structuredClone(domain || {});
  for (const container of DOMAIN_CONTAINERS) {
    const block = domain?.[container];
    if (!block) continue;
    for (const [name, def] of Object.entries(block)) {
      if (!def?.attributeUses?.some(u => isBindingAttribute(u.attribute))) continue;
      const { core, binding } = splitAttributeUses(def.attributeUses);
      if (binding.length) {
        if (!bindingDomain[container]) bindingDomain[container] = {};
        bindingDomain[container][name] = { attributeUses: binding };
        if (coreDomain[container]?.[name]) {
          coreDomain[container][name] = { ...coreDomain[container][name], attributeUses: core };
        }
      }
      // Move binding-only attributeTypes entirely
      if (container === 'attributeTypes' && isBindingAttribute(def.iri)) {
        if (!bindingDomain.attributeTypes) bindingDomain.attributeTypes = {};
        bindingDomain.attributeTypes[name] = structuredClone(def);
        delete coreDomain.attributeTypes[name];
      }
    }
  }
  return { coreDomain, bindingDomain };
}

module.exports = {
  DOMAIN_CONTAINERS,
  BINDING_ATTR_RE,
  isBindingAttribute,
  fragmentPaths,
  hasEnvelopeFragments,
  loadModuleEnvelope,
  mergeEnvelopeDocs,
  mergeDomain,
  serializeModuleDoc,
  mergedBytes,
  isMergedStale,
  extractBindingDomain,
  splitAttributeUses,
};
